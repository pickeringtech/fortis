//! LR 3.2, 4, 5, 6, 8, 9 and 16: parse isolated grammar rules.
use fortis_syntax::{lex, Parser};
use fortis_testkit::Json;
fn check(input: &Json, expect: &Json) {
    let mut source = input.get("source").unwrap().as_str().unwrap().to_string();
    let mut start = input.get("start").unwrap().as_str().unwrap();
    // Generated follow sets require statement and pattern delimiters.
    if start == "statement" { source = format!("{{ {source}\n}}"); start = "block"; }
    else if start == "pattern" { source = format!("match x {{ {source} => 0 }}"); start = "expr"; }
    let toks = lex(&source).unwrap();
    let result = Parser::new(&toks).parse(start);
    if expect == &Json::Bool(true) {
        let (_, fallbacks, _) = result.unwrap();
        assert_eq!(fallbacks, 0);
    } else {
        let err = result.unwrap_err();
        assert!(!err.expected.is_empty());
        assert!(err.line >= 1);
        let next = lex("x").unwrap();
        Parser::new(&next).parse("expr").unwrap();
    }
}
