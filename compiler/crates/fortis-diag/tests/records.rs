//! Published diagnostic schema, PROG-DIA-01: common and class-specific fields.
use fortis_diag::{Json, Record};
fn check(input: &Json, expect: &Json) {
    let record = Record::from_json(input);
    let valid = record.as_ref().map_or(false, |r| r.validate().is_empty());
    assert_eq!(Json::Bool(valid), *expect);
    if valid {
        let r = record.unwrap();
        assert_eq!(Json::parse(&r.to_json_line()).unwrap(), *input);
        assert!(r.render_text().contains(&r.code));
        assert!(r.render_text().contains(&r.message));
    }
}
