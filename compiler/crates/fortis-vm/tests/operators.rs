//! LR 5.6, 6.4, 6.5: the same operator values as the definitional evaluator.
use fortis_mir::model::{BinOp, Program};
use fortis_testkit::Json;
use fortis_vm::{machine::Vm, value::Value};
fn check(d: &Json, expect: &Json) {
    let typ = d.get("type").unwrap().as_str().unwrap();
    let v = |key| {
        let j = d.get(key).unwrap();
        match typ {
            "Int" => Value::Int(j.as_i64().unwrap() as i128),
            "String" => Value::str(j.as_str().unwrap()),
            "Float" => Value::Float(j.as_str().unwrap().parse().unwrap()),
            _ => panic!("unknown type"),
        }
    };
    let prog = Program::default();
    let mut vm = Vm::new(&prog, "unit");
    let result = vm
        .binary(
            BinOp::from_symbol(d.get("op").unwrap().as_str().unwrap()).unwrap(),
            v("a"),
            v("b"),
        )
        .unwrap();
    let actual = match result {
        Value::Int(n) => Json::Int(n as i64),
        Value::Bool(b) => Json::Bool(b),
        _ => panic!("unexpected result"),
    };
    assert_eq!(&actual, expect);
}

