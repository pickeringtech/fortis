//! LR 6.13: the complete built-in families, forbidden pairs and no search through a third type.
use fortis_testkit::Json;
use fortis_types::conversions;
fn check(input: &Json, expect: &Json) {
    let a = input.as_arr().unwrap();
    let src = a[0].as_str().unwrap(); let dst = a[1].as_str().unwrap();
    let conv = conversions::resolve(src, dst);
    let got = conv.as_ref().map(|c| Json::str(if c.fallible { "fallible" } else { "total" })).unwrap_or(Json::Null);
    assert_eq!(&got, expect);
    if let Some(c) = conv { assert_eq!((c.source.as_str(), c.target.as_str()), (src, dst)); }
}
#[test]
fn lr613_integer_total_iff_range_contains() {
    fortis_testkit::forall(|r| (r.between(0, 3), r.between(0, 3)), 200, None, |&(a,b)| {
        let names = ["Int8", "Int16", "UInt8", "UInt16"];
        let bounds = [(-128,127), (-32768,32767), (0,255), (0,65535)];
        let x = bounds[a as usize]; let y = bounds[b as usize];
        let conv = conversions::resolve(names[a as usize], names[b as usize]).unwrap();
        assert_eq!(conv.fallible, !(y.0 <= x.0 && x.1 <= y.1));
    });
}
