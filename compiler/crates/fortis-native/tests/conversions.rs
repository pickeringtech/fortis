//! LR 6.13: a conversion's code, complete payload and origin are part of its contract.
use fortis_native::{
    convert::*,
    failure::{Dyn, Failure},
};
use fortis_runtime::Decimal;
use fortis_testkit::Json;
fn check(d: &Json, expect: &Json) {
    let s = |k| d.get(k).unwrap().as_str().unwrap();
    let bounds = || {
        (
            s("low").parse::<i128>().unwrap(),
            s("high").parse::<i128>().unwrap(),
        )
    };
    let result: Result<String, Failure> = match (s("kind"), s("target")) {
        ("int", "Scalar") => {
            int_to_scalar(s("value").parse().unwrap(), "unit.origin").map(|c| c.to_string())
        }
        ("int", "Float") => {
            int_to_float(s("value").parse().unwrap(), "unit.origin").map(|n| format!("{n:.0}"))
        }
        ("int", _) => {
            let (lo, hi) = bounds();
            narrow::<i128>(s("value").parse().unwrap(), lo, hi, "unit.origin")
                .map(|n| n.to_string())
        }
        ("text", "Decimal") => parse_decimal(s("value"), "unit.origin").map(|d| d.to_string()),
        ("text", "Bool") => parse_bool(s("value"), "unit.origin").map(|b| b.to_string()),
        ("text", _) => {
            let (lo, hi) = bounds();
            parse_int::<i128>(s("value"), lo, hi, "unit.origin").map(|n| n.to_string())
        }
        ("decimal", _) => {
            let (lo, hi) = bounds();
            decimal_to_int::<i128>(&Decimal::parse(s("value")).unwrap(), lo, hi, "unit.origin")
                .map(|n| n.to_string())
        }
        ("bytes", _) => bytes_to_string(
            &d.get("value")
                .unwrap()
                .as_arr()
                .unwrap()
                .iter()
                .map(|n| n.as_i64().unwrap() as u8)
                .collect::<Vec<_>>(),
            "unit.origin",
        ),
        _ => panic!("unknown conversion"),
    };
    let actual = match result {
        Ok(v) => Json::str(v),
        Err(f) => {
            assert_eq!(f.origin, "unit.origin");
            Json::obj([
                ("code", Json::str(f.code)),
                (
                    "payload",
                    Json::obj(f.payload.into_iter().map(|(k, v)| {
                        (
                            k,
                            Json::str(match v {
                                Dyn::Int(n) => n.to_string(),
                                Dyn::Str(s) => s,
                                _ => panic!("unexpected payload"),
                            }),
                        )
                    })),
                ),
            ])
        }
    };
    assert_eq!(&actual, expect);
}

