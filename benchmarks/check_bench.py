"""PROG-NFR-04: clean frontend checks of 50k and 500k ordinary lines (DEL-40 criterion 5).

`python3 -I benchmarks/check_bench.py [--runs N] [--json]`

Each workload is generated by `benchmarks/check_workload.py` (deterministic; the preregistration records its
manifest sha256 and this tool refuses a workload whose manifest differs). Each run starts a new `fortisc check`
process over every module of the workload: the production frontend keeps no semantic cache between processes, so
every run is a cold check, and the time includes reading the files, parsing, names, declarations, typing, effects
and ownership, with no Cargo or download step. The run must accept every module (exit status 0, no records).
Reported: the median, minimum and maximum wall time over the runs, against the SHOULD budgets (5 s for 50k lines,
30 s for 500k).
"""
import hashlib
import json
import os
import statistics
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
FORTISC = os.path.join(ROOT, "compiler", "target", "release", "fortisc")
WORKLOADS = [("check-50k", 50000, 5.0), ("check-500k", 500000, 30.0)]
# the manifests the preregistration records (benchmarks/PREREGISTRATION-DEL-40.md)
MANIFESTS = {
    "check-50k": "57cc5e973dde9d3f815ee22ad6e9cf06ab51a49b137da7ce8b779fc40a6fb354",
    "check-500k": "d853dd3623af2fa649dc7413bc279b6ece039c7f4bec3a5d6ed1dd8aaa28b219",
}


def manifest(d):
    names = sorted(f for f in os.listdir(d) if f.endswith(".ft"))
    lines = [f"{hashlib.sha256(open(os.path.join(d, f), 'rb').read()).hexdigest()}  {f}" for f in names]
    return names, hashlib.sha256(("\n".join(lines) + "\n").encode()).hexdigest()


def main(argv):
    runs = int(argv[argv.index("--runs") + 1]) if "--runs" in argv else 5
    rows, ok = [], True
    for name, lines, budget in WORKLOADS:
        d = os.path.join(ROOT, "build", "bench", name)
        subprocess.run([sys.executable, "-I", os.path.join(HERE, "check_workload.py"), "--lines", str(lines), "--out", d], check=True, capture_output=True)
        files, digest = manifest(d)
        want = MANIFESTS.get(name)
        if want is not None and digest != want:
            print(f"{name}: the workload's manifest {digest} is not the preregistered {want}")
            ok = False
            continue
        n_lines = sum(1 for f in files for l in open(os.path.join(d, f), encoding="utf-8") if l.strip())
        times = []
        for _ in range(runs):
            t0 = time.perf_counter()
            r = subprocess.run([FORTISC, "check"] + [os.path.join(d, f) for f in files], capture_output=True, text=True)
            times.append(time.perf_counter() - t0)
            if r.returncode != 0 or r.stdout.strip() or r.stderr.strip():
                print(f"{name}: the check did not accept the workload: {(r.stdout + r.stderr)[:300]}")
                ok = False
                break
        med = statistics.median(times)
        row = {"workload": name, "modules": len(files), "lines": n_lines, "manifest_sha256": digest, "runs": len(times),
               "median_s": round(med, 3), "min_s": round(min(times), 3), "max_s": round(max(times), 3),
               "budget_s": budget, "met": med <= budget, "lines_per_s": round(n_lines / med)}
        rows.append(row)
        print(f"{name}: {len(files)} modules, {n_lines} lines; median {med:.3f} s (min {min(times):.3f}, max {max(times):.3f}) over {len(times)} cold runs; "
              f"budget {budget:.0f} s {'met' if row['met'] else 'NOT met'}; {row['lines_per_s']} lines/s")
    if "--json" in argv:
        os.makedirs(os.path.join(ROOT, "build", "bench"), exist_ok=True)
        json.dump({"rule": "PROG-NFR-04", "rows": rows}, open(os.path.join(ROOT, "build", "bench", "check-results.json"), "w"), indent=1)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
