"""SP-08 and the Dependency injection kit (Platform 3): the elaboration's corpus, determinism, rule classes,
lazy-edge representations and provenance under `noalloc`.

`python3 -I conformance/tools/di_check.py [--json] [--permutations N] [--seed S]`

1. **Corpus** (conformance/di): each `// execute:` program is clean under both checkers (the production checker and
   the reference checker, each over the elaborated module) and prints the expected line on the reference
   interpreter, the VM and native; each `// reject: CODE` program gets CODE at the marked line from both checkers.
   Package fixtures (conformance/di/packages) run on the VM and native.
2. **Determinism** (Platform 3.3): every execute program is permuted N times (the statements of each context body,
   the module's top-level declarations, the imports); the generated declarations (`fortisc elaborate`, after the
   generated-code marker) and the plans (`fortisc elaborate --plan`) are byte-identical to the original's.
3. **No parallel borrow rules**: every record the kit itself emits across the corpus is of the class
   Dependency injection with a PLAT-03 rule; ownership, effect and type findings on DI programs come from the core
   checkers over the elaborated code (the core-judged fixtures).
4. **Static provenance** (Platform 3.5): each plan names, for every slot, the consumer, the slot, the chosen
   binding, the context, the level, the specificity, the reason and the rejected candidates; a package's plan
   names `name@version`; the plan carries no line numbers.
5. **Lazy edges** (spikes/SP-08/lazy): the three representations of design section 8, each with its expected
   verdict.
6. **Provenance under noalloc** (spikes/SP-08/noalloc): the three wirings are accepted with the same output on
   every backend, and their live-provenance event streams are equal on the three backends; the allocator probe's
   counts per phase for each probed function are reported with the phases it visited (a pending poll, a
   never-polled drop), and the probe itself is calibrated first (fortis-native's calibration test: an allocating
   future is counted in every phase, a quiet one in none).
7. **The core's verdict** (Codex review finding 4): each program's elaborated text, checked as an ordinary module by
   both checkers, gives exactly the DI program's records (located through the elaboration's line origins), and the
   elaboration changes a consumer only by removing the word `inject`.

Every command's exit status is checked: a checker that fails without records, an elaboration that fails, or a run
that prints the expected line and then fails is a failed check.

Writes build/di-check.json with --json.
"""
import json
import os
import random
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
# the corpus reads captured values, so it runs under the permit-all telemetry plan (Language Reference 15; D-25)
os.environ.setdefault("FORTIS_TELEMETRY", "permit-all")
FORTISC = os.path.join(ROOT, "compiler", "target", "release", "fortisc")
FORTIS = os.path.join(ROOT, "bin", "fortis")
CORPUS = os.path.join(ROOT, "conformance", "di")
SPIKE = os.path.join(ROOT, "spikes", "SP-08")
MARKER = "// fortis: generated by fortis.di"


def run(args, env=None, timeout=1800, cwd=ROOT):
    r = subprocess.run(args, capture_output=True, text=True, cwd=cwd, env={**os.environ, **(env or {})}, timeout=timeout)
    return r.returncode, r.stdout, r.stderr


def records(text):
    return [json.loads(l) for l in text.splitlines() if l.startswith("{") and '"code"' in l]


def header(path):
    first = open(path, encoding="utf-8").readline().strip()
    m = re.match(r"// execute: (.*)", first)
    if m:
        return "execute", m.group(1)
    m = re.match(r"// reject: (\S+)", first)
    if m:
        lines = open(path, encoding="utf-8").read().split("\n")
        mark = next((i + 1 for i, l in enumerate(lines) if f"// reject: {m.group(1)} —" in l), None)
        return "reject", (m.group(1), mark)
    return None, None


def observed(out):
    return next((l[len("observed: "):] for l in out.splitlines() if l.startswith("observed: ")), None)


def interpreter(path):
    """The reference interpreter's output, or a failure marker when it exits with an error."""
    code, out, err = run([sys.executable, "-I", FORTIS, "run", path])
    text = "|".join(l for l in out.splitlines() if l)
    return text if code == 0 else f"exit {code}: {text} {err.strip()[-200:]}"


def backend(cmd, path, env=None):
    """The VM's or native's observed line, or a failure marker when the command exits with an error."""
    code, out, err = run([FORTISC, cmd, path], env=env)
    o = observed(out)
    return (o if code == 0 else f"exit {code}: {o}"), out, err


def checkers(path, expect_clean=None):
    """(production records, reference records, exit statuses as expected) for one file: a clean check exits 0 with
    no record, a rejected one exits non-zero with records."""
    c1, out, _ = run([FORTISC, "check", "--format", "json", path])
    c2, rout, _ = run([sys.executable, "-I", FORTIS, "check", "--format", "json", path])
    prod, ref = records(out), records(rout)
    statuses = all((c == 0) == (not rs) for c, rs in ((c1, prod), (c2, ref)))
    return prod, ref, statuses


def generated(path):
    """(the generated declarations, the plans, both elaboration runs exited 0)."""
    c1, out, err = run([FORTISC, "elaborate", path])
    text = out[out.find(MARKER):] if MARKER in out else ""
    c2, plan, _ = run([FORTISC, "elaborate", "--plan", path])
    return text, plan, c1 == 0 and c2 == 0


def events(stdout, stderr):
    """The observation events of a run, as (event, binding, level) in order, from any backend's record stream."""
    out = []
    for l in (stdout + "\n" + stderr).splitlines():
        l = l[len("record: "):] if l.startswith("record: ") else l
        if '"observation-event"' in l:
            f = json.loads(l)["fields"]
            out.append((f["event"], f["binding"], f["level"]))
        elif l.startswith("kind=observation-event"):
            f = dict(kv.split("=") for kv in l.split("fields=")[1].split(","))
            out.append((f["event"], f["binding"], f["level"]))
    return out


def core_verdict(rel):
    """The records of the elaborated text checked as an ordinary module by both checkers, each located back
    through the elaboration's origins: what the core alone says about the program (None when elaboration fails)."""
    code, out, err = run([FORTISC, "elaborate", "--origins", rel])
    origins = next((json.loads(l)["origins"] for l in err.splitlines() if l.startswith('{"origins"')), None)
    if code != 0 or origins is None:
        return None
    with tempfile.TemporaryDirectory() as tmp:
        plain = os.path.join(tmp, os.path.basename(rel))
        open(plain, "w", encoding="utf-8").write(out[:-1] if out.endswith("\n") else out)
        prod, ref, ok = checkers(plain)
    locate = lambda rs: sorted({(r["code"], origins[r["line"] - 1] if 0 < r["line"] <= len(origins) else r["line"]) for r in rs})
    return locate(prod), locate(ref), ok


def rewrite_ok(rel):
    """The elaboration keeps every source line except that a slot loses `inject` (and `lazy`) and a context's lines
    are emptied."""
    src = open(os.path.join(ROOT, rel), encoding="utf-8").read().split("\n")
    code, out, _ = run([FORTISC, "elaborate", rel])
    got = out.split("\n")[:len(src)]
    contexts, inside = set(), False
    for i, l in enumerate(src):
        if l.startswith("context "):
            inside = True
        if inside:
            contexts.add(i)
            if l.startswith("}"):
                inside = False
    for i, (a, b) in enumerate(zip(src, got)):
        if i in contexts:
            if b.strip():
                return f"line {i + 1}: a context line is not emptied"
        elif re.search(r"\binject\b", a.split("//")[0]):
            # a slot's line must lose the word: an unchanged slot would leave a field the generated code cannot fill
            if re.sub(r"\binject +(lazy +)?", "", a, count=1) != b:
                return f"line {i + 1}: the slot {a!r} became {b!r}"
        elif a != b:
            return f"line {i + 1}: {a!r} became {b!r}"
    return None if code == 0 else f"elaboration exited {code}"


def permute(src, rnd):
    """The module with its context bodies, top-level declarations and imports reordered."""
    lines = src.split("\n")
    head = []
    while lines and lines[0].startswith("//"):
        head.append(lines.pop(0))
    imports = [l for l in lines if l.startswith("import ")]
    rest = "\n".join(l for l in lines if not l.startswith("import "))
    blocks = [b for b in re.split(r"\n\s*\n", rest.strip("\n")) if b.strip()]
    out = []
    for b in blocks:
        m = re.match(r"(context [^\n]*\{)\n(.*)\n\}$", b, re.S)
        if m:
            # every statement moves, `parent` included; a `provide` continued on the next line moves whole
            stmts = []
            for l in m.group(2).split("\n"):
                if stmts and l.strip().startswith(("to ", "to[", "replaces", "{")):
                    stmts[-1] += "\n" + l
                else:
                    stmts.append(l)
            rnd.shuffle(stmts)
            b = "\n".join([m.group(1)] + stmts + ["}"])
        out.append(b)
    rnd.shuffle(out)
    rnd.shuffle(imports)
    return "\n".join(head + imports + [""] + ["\n\n".join(out)]) + "\n"


def main(argv):
    def opt(name, default):
        return argv[argv.index(name) + 1] if name in argv else default
    n_perm = int(opt("--permutations", "20"))
    rnd = random.Random(int(opt("--seed", "8")))
    rows, problems = [], []

    def expect(section, name, ok, detail=""):
        rows.append({"section": section, "check": name, "ok": bool(ok), "detail": str(detail)[:400]})
        if not ok:
            problems.append(f"{section}: {name}: {str(detail)[:300]}")
        print(f"{'PASS' if ok else 'FAIL'} [{section}] {name}" + ("" if ok else f": {str(detail)[:300]}"))

    files = sorted(os.path.join(CORPUS, f) for f in os.listdir(CORPUS) if f.endswith(".ft"))
    noalloc = [os.path.join(SPIKE, "noalloc", f + ".ft") for f in ("wiring", "wiring_provenance")]
    kit_records = []
    core_judged = []
    # 1. corpus, and 7. the core's verdict on each program's elaborated text
    for path in files:
        rel = os.path.relpath(path, ROOT)
        kind, want = header(path)
        prod, ref, statuses = checkers(rel)
        kit_records += [r for r in prod if r["code"].startswith("E-DI")]
        if kind == "execute":
            expect("corpus", f"{rel}: clean under both checkers, which exit 0", not prod and not ref and statuses, [r["code"] for r in prod + ref])
            got = {"interpreter": interpreter(rel), "vm": backend("vm", rel)[0], "native": backend("native", rel)[0]}
            expect("corpus", f"{rel}: interpreter, VM and native print the expected line and exit 0", all(v == want for v in got.values()), got)
        elif kind == "reject":
            code, line = want
            hit = lambda rs: any(r["code"] == code and r["line"] == line for r in rs)
            expect("corpus", f"{rel}: {code} at line {line} from both checkers, which exit non-zero", hit(prod) and hit(ref) and statuses, ([(r["code"], r["line"]) for r in prod], [(r["code"], r["line"]) for r in ref]))
            if not code.startswith("E-DI"):
                core_judged.append((rel, code))
        if kind == "execute" or (kind == "reject" and not want[0].startswith("E-DI")):
            verdict = core_verdict(rel)
            mine = sorted({(r["code"], r["line"]) for r in prod})
            expect("core", f"{rel}: the core's verdict on the elaborated text is the program's ({mine or 'clean'})", verdict is not None and verdict[0] == mine and verdict[1] == sorted({(r["code"], r["line"]) for r in ref}) and verdict[2], verdict)
            bad = rewrite_ok(rel)
            expect("core", f"{rel}: the elaboration changes a consumer only by removing `inject`", bad is None, bad)
    for pkg in sorted(os.listdir(os.path.join(CORPUS, "packages"))):
        rel = os.path.relpath(os.path.join(CORPUS, "packages", pkg), ROOT)
        entry = os.path.join(rel, "src", "app.ft")
        kind, want = header(os.path.join(ROOT, entry))
        c, out, _ = run([FORTISC, "check", "--format", "json", rel])
        prod = records(out)
        got = {"vm": backend("vm", rel)[0], "native": backend("native", rel)[0]}
        expect("corpus", f"{rel}: clean (exit 0), and the VM and native print the expected line", c == 0 and not prod and all(v == want for v in got.values()), (prod[:2], got))
        plan = [json.loads(l) for l in run([FORTISC, "elaborate", "--plan", entry])[1].splitlines() if l.startswith("{")]
        manifest = open(os.path.join(ROOT, rel, "project.yaml")).read()
        name = re.search(r"^name: (\S+)", manifest, re.M).group(1)
        version = re.search(r"^version: (\S+)", manifest, re.M).group(1)
        expect("provenance", f"{rel}: the plan names the package and its version", plan and all(p["package"] == f"{name}@{version}" for p in plan), [p.get("package") for p in plan])
    # 2. determinism: the execute programs, the noalloc wirings (live provenance included) and the package
    subjects = [os.path.relpath(p, ROOT) for p in files if header(p)[0] == "execute"] + [os.path.relpath(p, ROOT) for p in noalloc]
    for rel in subjects:
        base_gen, base_plan, ok = generated(rel)
        src = open(os.path.join(ROOT, rel), encoding="utf-8").read()
        differ, failed = [], []
        with tempfile.TemporaryDirectory() as tmp:
            for k in range(n_perm):
                p = os.path.join(tmp, os.path.basename(rel))
                open(p, "w", encoding="utf-8").write(permute(src, rnd))
                g, pl, gok = generated(p)
                c, out, _ = run([FORTISC, "check", "--format", "json", p])
                if not gok or c != 0:
                    failed.append(k)
                elif g != base_gen or pl != base_plan:
                    differ.append(k)
        expect("determinism", f"{rel}: {n_perm} permutations of its declarations, context statements (`parent` included) and imports elaborate and check, with byte-identical generated code and plans", ok and base_gen and not differ and not failed, {"differ": differ[:5], "failed": failed[:5]})
    for pkg in sorted(os.listdir(os.path.join(CORPUS, "packages"))):
        src_pkg = os.path.join(CORPUS, "packages", pkg)
        entry = os.path.join(src_pkg, "src", "app.ft")
        base_gen, base_plan, ok = generated(os.path.relpath(entry, ROOT))
        src = open(entry, encoding="utf-8").read()
        differ, failed = [], []
        with tempfile.TemporaryDirectory() as tmp:
            dst = os.path.join(tmp, pkg)
            subprocess.run(["cp", "-r", src_pkg, dst], check=True)
            for k in range(n_perm):
                open(os.path.join(dst, "src", "app.ft"), "w", encoding="utf-8").write(permute(src, rnd))
                g, pl, gok = generated(os.path.join(dst, "src", "app.ft"))
                c, _, _ = run([FORTISC, "check", "--format", "json", dst])
                if not gok or c != 0:
                    failed.append(k)
                elif g != base_gen or pl != base_plan:
                    differ.append(k)
        expect("determinism", f"{os.path.relpath(src_pkg, ROOT)}: {n_perm} permutations of the context module's declarations, statements and imports (an unrelated module declares the same names) elaborate and check, with byte-identical generated code and plans", ok and base_gen and not differ and not failed, {"differ": differ[:5], "failed": failed[:5]})
    # 3. rule classes
    bad = [r for r in kit_records if r.get("class") != "Dependency injection" or not r.get("rule", "").startswith("PLAT-03-")]
    expect("rules", f"the kit's own {len(kit_records)} records are Dependency injection records with PLAT-03 rules", kit_records and not bad, bad[:3])
    expect("rules", f"{len(core_judged)} rejections of DI programs are the core's own (ownership and type codes, located at the binding)", core_judged and all(not c.startswith("E-DI") for _, c in core_judged), core_judged)
    # 4. static provenance
    keys = {"consumer", "slot", "key", "form", "chosen", "context", "level", "specificity", "reason", "rejected"}
    for rel in subjects:
        c, out, _ = run([FORTISC, "elaborate", "--plan", rel])
        plans = [json.loads(l) for l in out.splitlines() if l.startswith("{")]
        slots = [s for p in plans for s in p["slots"]]
        expect("provenance", f"{rel}: every slot's plan entry is complete and the plan has no line numbers", c == 0 and plans and all(keys <= set(s) for s in slots) and '"line"' not in json.dumps(plans), [sorted(keys - set(s)) for s in slots if not keys <= set(s)][:2])
    # 5. lazy edges
    for f in sorted(os.listdir(os.path.join(SPIKE, "lazy"))):
        rel = os.path.relpath(os.path.join(SPIKE, "lazy", f), ROOT)
        kind, want = header(os.path.join(ROOT, rel))
        if kind == "reject":
            prod, ref, statuses = checkers(rel)
            code, line = want
            expect("lazy", f"{rel}: {code} at line {line} from both checkers", statuses and any(r["code"] == code and r["line"] == line for r in prod) and any(r["code"] == code and r["line"] == line for r in ref), [(r["code"], r["line"]) for r in prod])
        else:
            got = {"interpreter": interpreter(rel), "vm": backend("vm", rel)[0], "native": backend("native", rel)[0]}
            expect("lazy", f"{rel}: runs with the stated result on every backend", all(v == want for v in got.values()), got)
    # 6. provenance under noalloc: calibration, then the wirings
    c, out, err = run(["cargo", "test", "--offline", "-q", "-p", "fortis-native", "--features", "alloc-probe", "--release", "calibration"], cwd=os.path.join(ROOT, "compiler"), timeout=3600)
    expect("noalloc", "the allocator probe is calibrated: an allocating future is counted in every phase, a quiet one in none", c == 0 and "1 passed" in out, (out + err)[-300:])
    probes = {}
    streams = {}
    for f in ("wiring", "wiring_provenance", "wiring_names"):
        rel = os.path.relpath(os.path.join(SPIKE, "noalloc", f + ".ft"), ROOT)
        kind, want = header(os.path.join(ROOT, rel))
        prod, ref, statuses = checkers(rel)
        ic, iout, ierr = run([sys.executable, "-I", FORTIS, "run", rel])
        vm, vout, verr = backend("vm", rel)
        nat, nout, nerr = backend("native", rel, env={"FORTIS_ALLOC_PROBE": "1"})
        got = {"interpreter": "|".join(l for l in iout.splitlines() if l) if ic == 0 else f"exit {ic}", "vm": vm, "native": nat}
        streams[f] = {"interpreter": events(iout, ierr), "vm": events(vout, verr), "native": events(nout, nerr)}
        probe = next((json.loads(l[len("record: "):]) for l in (nout + nerr).splitlines() if l.startswith("record: ") and '"alloc-probe"' in l), None)
        fns = {x["function"]: x for x in (probe or {}).get("functions", [])}
        probes[f] = {"checkers": [r["code"] for r in prod + ref], "outputs": got, "probe": fns}
        expect("noalloc", f"{rel}: accepted by both checkers and the same output on every backend", not prod and not ref and statuses and all(v == want for v in got.values()), (probes[f]["checkers"], got))
        h = fns.get("handle")
        expect("noalloc", f"{rel}: the probe measured `handle` through a pending poll and a completed drop", h and h["futures"] >= 2 and h["polls"] >= 1 and h["dropped_after"] >= 1, h)
        if f == "wiring":
            b = fns.get("build")
            expect("noalloc", f"{rel}: the probe measured `build` (a scope built inside noalloc code) including a never-polled drop", b and b["futures"] >= 2 and b["dropped_before"] >= 1, b)
        counts = {n: {k: x[k] for k in ("construct", "poll", "complete", "drop_before", "drop_after")} for n, x in fns.items()}
        probes[f]["allocations"] = counts
        print(f"     allocations per phase in {f}: {counts}")
    for f in ("wiring_provenance", "wiring_names"):
        st = streams[f]
        kinds = {e[0] for e in st["native"]}
        expect("noalloc", f"{f}: the live-provenance event streams are equal on the interpreter, the VM and native, with creation, reuse and disposal", st["native"] and st["interpreter"] == st["vm"] == st["native"] and kinds == {"1", "2", "3"}, {k: len(v) for k, v in st.items()})
    expect("noalloc", "the wiring without provenance allocates nothing in any phase of any probed function", probes["wiring"]["allocations"] and not any(v for x in probes["wiring"]["allocations"].values() for v in x.values()), probes["wiring"]["allocations"])
    if "--json" in argv:
        os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
        json.dump({"rule": "SP-08", "checks": rows, "noalloc": probes, "streams": {k: v["native"] for k, v in streams.items()}, "permutations": n_perm}, open(os.path.join(ROOT, "build", "di-check.json"), "w"), indent=1)
    print(f"\n{len(rows)} checks, {sum(r['ok'] for r in rows)} pass")
    print("di check: " + ("OK" if not problems else f"{len(problems)} problems"))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
