#!/usr/bin/env python3
"""Generate the shared Unicode grapheme properties, offline and without dependencies.

Python's Unicode general categories supply the mark sets. The committed Unicode
15.1 property differences supply what unicodedata does not expose: Extend and
SpacingMark exceptions, emoji, controls, prepend characters and Indic conjuncts.
The source URLs and both Unicode versions are recorded with those differences.
Run with Python 3.12 (unicodedata 15.0.0); --check refuses stale generated files.
"""
import argparse
import json
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[2]


def expand(ranges):
    return {n for a, b in ranges for n in range(int(a, 16), int(b, 16) + 1)}


def compact(points):
    ranges = []
    for n in sorted(points):
        if ranges and n == ranges[-1][1] + 1:
            ranges[-1][1] = n
        else:
            ranges.append([n, n])
    return ranges


def generated():
    data = json.loads((ROOT / 'conformance/unicode/grapheme-properties.json').read_text())
    if unicodedata.unidata_version != data['unicodedata_version']:
        raise SystemExit('grapheme generation requires unicodedata ' + data['unicodedata_version'])
    base = {'Extend': set(), 'SpacingMark': set()}
    for n in range(0x110000):
        category = unicodedata.category(chr(n))
        if category in ('Mn', 'Me'):
            base['Extend'].add(n)
        elif category == 'Mc':
            base['SpacingMark'].add(n)
    header = (f"Generated by conformance/tools/gen_graphemes.py; Unicode {data['unicode_version']}; "
              f"unicodedata {data['unicodedata_version']}. Do not edit.")
    py = '# ' + header + '\n'
    rust = '// ' + header + '\n'
    for name, spec in sorted(data['properties'].items()):
        if name in ('CR', 'LF'):  # the segmentation rules spell these two scalars directly
            continue
        points = expand(spec['ranges']) if 'ranges' in spec else (base[name] | expand(spec['add'])) - expand(spec['remove'])
        name = name.upper()
        ranges = compact(points)
        py += f'{name} = (\n' + ''.join(f'    (0x{a:X}, 0x{b:X}),\n' for a, b in ranges) + ')\n'
        rust += f'pub const {name}: &[(u32, u32)] = &[\n' + ''.join(f'    (0x{a:X}, 0x{b:X}),\n' for a, b in ranges) + '];\n'
    return {'interpreter/grapheme_data.py': py, 'compiler/crates/fortis-runtime/src/grapheme_data.rs': rust}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in generated().items():
        path = ROOT / path
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        raise SystemExit('stale grapheme tables: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
